#!/usr/bin/env python3
"""genassets.py — generate AirRadar v7 LVGL image assets (.c, LV_IMG_CF_TRUE_COLOR_ALPHA).

All glyphs are drawn pure white on transparent at 4x supersampling and
downscaled with Lanczos, so LVGL img_recolor can tint them at runtime.
Output: firmware/AirRadar/src/assets/img_*.c
"""
import os
from PIL import Image, ImageDraw

SS = 4  # supersample factor
OUT = os.path.join(os.path.dirname(__file__), "..", "AirRadar", "src", "assets")
os.makedirs(OUT, exist_ok=True)

def canvas(w, h):
    return Image.new("RGBA", (w * SS, h * SS), (0, 0, 0, 0))

def emit(img, name):
    w, h = img.size
    img = img.resize((w // SS, h // SS), Image.LANCZOS)
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        b = bytearray()
        for x in range(w):
            r, g, bl, a = px[x, y]
            c565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (bl >> 3)
            b += bytes((c565 & 0xFF, c565 >> 8, a))     # lo, hi, alpha
        rows.append(", ".join(f"0x{v:02x}" for v in b))
    body = ",\n  ".join(rows)
    c = f"""// generated by tools/genassets.py — do not edit
#include <lvgl.h>

static const uint8_t {name}_map[] = {{
  {body}
}};

const lv_img_dsc_t {name} = {{
  .header = {{ .cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0,
              .w = {w}, .h = {h} }},
  .data_size = sizeof({name}_map),
  .data = {name}_map,
}};
"""
    with open(os.path.join(OUT, f"{name}.c"), "w") as f:
        f.write(c)
    print(f"{name}: {w}x{h}  {w*h*3} bytes")

